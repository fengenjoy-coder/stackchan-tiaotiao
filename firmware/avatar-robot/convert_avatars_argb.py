#!/usr/bin/env python3
"""ARGB8888 variant of convert_avatars.py — preserves PNG alpha.

The stock converter emits opaque RGB565 (no alpha channel), so the avatar
always renders as a solid box over the light-theme UI. This variant emits
LV_COLOR_FORMAT_ARGB8888 images (160x120x4 = 75 KB/frame, 14 frames ≈ 1 MB)
so the avatar background can be transparent and the stock UI background
shows through. Pixel layout per LVGL 9 ARGB8888: little-endian uint32
0xAARRGGBB => bytes B,G,R,A.

Usage: python3 convert_avatars_argb.py [--src ~/.stackchan/avatar]
"""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

DEFAULT_SRC = Path.home() / ".stackchan" / "avatar"
DEFAULT_OUT = Path(__file__).resolve().parent.parent.parent / "main" / "boards" / "stackchan"

FRAMES = [
    "idle", "happy", "thinking", "sad", "surprised", "embarrassed",
    "eyes_open", "eyes_half", "eyes_closed",
    "mouth_closed", "mouth_half", "mouth_open", "mouth_e", "mouth_u",
]
TARGET_W = 128
TARGET_H = 96


def rgba_to_argb8888_bytes(im: Image.Image) -> bytes:
    if im.mode != "RGBA":
        im = im.convert("RGBA")
    px = im.tobytes()  # R,G,B,A per pixel
    out = bytearray(len(px))
    for i in range(0, len(px), 4):
        out[i] = px[i + 2]      # B
        out[i + 1] = px[i + 1]  # G
        out[i + 2] = px[i]      # R
        out[i + 3] = px[i + 3]  # A
    return bytes(out)


def emit_array(name: str, data: bytes) -> str:
    lines = [f"static const LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def emit_dsc(name: str, w: int, h: int, data_size: int) -> str:
    return (
        f"const lv_image_dsc_t {name} = {{\n"
        f"    .header = {{\n"
        f"        .magic = LV_IMAGE_HEADER_MAGIC,\n"
        f"        .cf = LV_COLOR_FORMAT_ARGB8888,\n"
        f"        .flags = 0,\n"
        f"        .w = {w},\n"
        f"        .h = {h},\n"
        f"        .stride = {w * 4},\n"
        f"        .reserved_2 = 0,\n"
        f"    }},\n"
        f"    .data_size = {data_size},\n"
        f"    .data = {name}_map,\n"
        f"    .reserved = NULL,\n"
        f"    .reserved_2 = NULL,\n"
        f"}};\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    arrays, decls = [], []
    total = 0
    for frame in FRAMES:
        png = args.src / f"{frame}.png"
        if not png.exists():
            print(f"SKIP {png} (missing)")
            continue
        im = Image.open(png).resize((TARGET_W, TARGET_H), Image.LANCZOS)
        data = rgba_to_argb8888_bytes(im)
        symbol = f"avatar_{frame}"
        arrays.append(emit_array(symbol, data))
        decls.append(emit_dsc(symbol, TARGET_W, TARGET_H, len(data)))
        total += len(data)
        print(f"  {frame:14s} -> {len(data)} bytes (160x120 ARGB8888)")

    guard = "AVATAR_IMAGES_LOCAL_H"
    header = (
        f"#pragma once\n"
        f"// Auto-generated by convert_avatars_argb.py — ARGB8888 transparent variant.\n"
        f"// Include AFTER the stock avatar_images.h so these symbols win at link time.\n"
        f"#ifndef {guard}\n#define {guard}\n"
        f"#include <lvgl.h>\n"
        + "\n".join(f"extern const lv_image_dsc_t avatar_{f};" for f in FRAMES
                    if (args.src / f"{f}.png").exists())
        + f"\n#endif // {guard}\n"
    )
    source = (
        "#include \"avatar_images.local.h\"\n\n" + "\n\n".join(arrays + decls) + "\n"
    )
    (args.out_dir / "avatar_images.local.h").write_text(header, encoding="utf-8")
    (args.out_dir / "avatar_images.local.cc").write_text(source, encoding="utf-8")
    print(f"\nTotal: {total} bytes ({total / 1024:.0f} KB)")
    print(f"Wrote: {args.out_dir / 'avatar_images.local.cc'}")
    print(f"Wrote: {args.out_dir / 'avatar_images.local.h'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
